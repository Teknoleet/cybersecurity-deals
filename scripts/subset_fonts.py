"""Rebuild the self-hosted WOFF2 web fonts from the original TTF instances.

Development tool only; not used by the site build or the collector. Requires
``python3 -m pip install fonttools==4.60.1 brotli==1.1.0``.

The source TTFs are the Google Fonts static instances that the site served
before this script existed. Recover them from Git history when needed:

    mkdir -p /tmp/font-src
    for f in $(git ls-tree --name-only f27d052 web/public/fonts/ | grep '\\.ttf$'); do
        git show f27d052:$f > /tmp/font-src/$(basename $f); done
    python3 scripts/subset_fonts.py /tmp/font-src

Inter (OFL, no Reserved Font Name) is split into a small Latin file and an
"ext" file for every other script it supports. The CSS ``unicode-range``
means browsers fetch the ext file only for pages that use those characters,
so rendering is unchanged for any text. IBM Plex Mono carries the Reserved
Font Name "Plex"; removing glyphs would make an OFL Modified Version that
must be renamed, so it is only converted to WOFF2 with every glyph and name
kept. File names carry a content hash so ``/fonts/*`` can be cached
immutably. The generated ``@font-face`` rules replace the block between the
markers in ``web/assets/styles.css``.
"""
from __future__ import annotations

import argparse
import hashlib
import io
from pathlib import Path
import re

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'web/public/fonts'
STYLES = ROOT / 'web/assets/styles.css'
START, END = '/* fonts:start (generated by scripts/subset_fonts.py) */', '/* fonts:end */'

# Google Fonts' "latin" range, plus arrows, the search glyph and currency signs the site uses.
LATIN = [(0x0000, 0x00FF), (0x0131, 0x0131), (0x0152, 0x0153), (0x02BB, 0x02BC), (0x02C6, 0x02C6),
         (0x02DA, 0x02DA), (0x02DC, 0x02DC), (0x0304, 0x0304), (0x0308, 0x0308), (0x0329, 0x0329),
         (0x2000, 0x206F), (0x20A0, 0x20CF), (0x2122, 0x2122), (0x2190, 0x2199), (0x2212, 0x2212),
         (0x2215, 0x2215), (0x2315, 0x2315), (0xFEFF, 0xFEFF), (0xFFFD, 0xFFFD)]

# Source file -> (family, weight, subset?)
SOURCES = {
    'UcCO3FwrK3iLTeHuS_nVMrMxCp50SjIw2boKoduKmMEVuLyfMZg.ttf': ('Inter', 400, True),
    'UcCO3FwrK3iLTeHuS_nVMrMxCp50SjIw2boKoduKmMEVuI6fMZg.ttf': ('Inter', 500, True),
    'UcCO3FwrK3iLTeHuS_nVMrMxCp50SjIw2boKoduKmMEVuGKYMZg.ttf': ('Inter', 600, True),
    'UcCO3FwrK3iLTeHuS_nVMrMxCp50SjIw2boKoduKmMEVuFuYMZg.ttf': ('Inter', 700, True),
    'UcCO3FwrK3iLTeHuS_nVMrMxCp50SjIw2boKoduKmMEVuDyYMZg.ttf': ('Inter', 800, True),
    '-F63fjptAgt5VM-kVkqdyU8n5ig.ttf': ('IBM Plex Mono', 400, False),
    '-F6qfjptAgt5VM-kVkqdyU8n3twJ8lc.ttf': ('IBM Plex Mono', 500, False),
}


def in_latin(cp):
    return any(lo <= cp <= hi for lo, hi in LATIN)


def ranges(codepoints):
    """Collapse sorted code points into CSS unicode-range terms."""
    terms, run = [], None
    for cp in sorted(codepoints):
        if run and cp == run[1] + 1:
            run[1] = cp
            continue
        if run:
            terms.append(run)
        run = [cp, cp]
    if run:
        terms.append(run)
    return ', '.join(f'U+{a:04X}' if a == b else f'U+{a:04X}-{b:04X}' for a, b in terms)


def woff2(path, unicodes=None):
    font = TTFont(path, recalcTimestamp=False)  # Byte-reproducible output and file names.
    if unicodes is not None:
        options = subset.Options()
        options.layout_features = ['*']   # Keep kerning, ligatures and alternates.
        options.name_IDs = ['*']          # Keep copyright, licence and version records.
        options.name_languages = ['*']
        options.notdef_outline = True
        options.glyph_names = False
        subsetter = subset.Subsetter(options)
        subsetter.populate(unicodes=unicodes)
        subsetter.subset(font)
    font.flavor = 'woff2'
    buffer = io.BytesIO()
    font.save(buffer, reorderTables=False)
    return buffer.getvalue()


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('source', type=Path, help='directory holding the original TTF files')
    args = parser.parse_args(argv)
    for old in OUT.glob('*.woff2'):
        old.unlink()
    rules = []
    for name, (family, weight, split) in SOURCES.items():
        path = args.source / name
        cmap = set(TTFont(path).getBestCmap())
        parts = [('latin', {cp for cp in cmap if in_latin(cp)}), ('ext', {cp for cp in cmap if not in_latin(cp)})] if split else [('all', None)]
        for label, unicodes in parts:
            data = woff2(path, unicodes)
            slug = re.sub(r'[^a-z0-9]+', '-', family.lower()).strip('-')
            target = f'{slug}-{weight}-{label}.{hashlib.sha256(data).hexdigest()[:10]}.woff2'
            (OUT / target).write_bytes(data)
            unicode_range = f'\n  unicode-range: {ranges(unicodes)};' if unicodes is not None else ''
            rules.append(f"@font-face {{\n  font-family: '{family}';\n  font-style: normal;\n  font-weight: {weight};\n"
                         f"  font-display: swap;\n  src: url(/fonts/{target}) format('woff2');{unicode_range}\n}}")
            print(f'{target}: {len(data):,} bytes')
    styles = STYLES.read_text(encoding='utf-8')
    if styles.count(START) != 1 or styles.count(END) != 1:
        raise SystemExit(f'{STYLES} must contain exactly one font marker block')
    head, rest = styles.split(START)
    _, tail = rest.split(END)
    STYLES.write_text(head + START + '\n' + '\n'.join(rules) + '\n' + END + tail, encoding='utf-8')


if __name__ == '__main__':
    main()
